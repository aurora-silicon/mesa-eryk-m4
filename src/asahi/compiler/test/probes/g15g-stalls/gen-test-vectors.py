#!/usr/bin/env python3
"""Regenerate ../../agx3_g15g_stall_vectors.h from run-corpus.sh's vectors.txt.

usage: gen-test-vectors.py WORK/vectors.txt > ../../agx3_g15g_stall_vectors.h"""
import sys

SELECTED = {
    'main/f32_sqrt': 'rld and lddev producers, one stall each',
    'main/f32_sin': 'forward bn displacements across a stall',
    'main/tex_sample': 'smp waits on staging copies: no stall; stdev waits on smp: stall',
    'main/atomic_ret': 'device atomic result read back through staging: no stall',
    'main/atomic_cas': 'atomic waiting on a GPR operand load: stall',
    'main/tg_basic': 'threadgroup loads',
    'main/cf_loop_load': 'backward b displacement across a stall',
    'main/simd_bcast_first': 'subgroup op after a special-register read',
    'targeted/w_atomic_chain': 'a wait inside a skipped predicated region does not count',
    'targeted/w_pointer_chase': 'loop-carried load consumed at the loop head',
    'targeted/w_switch_loads': 'waits at the join of several predicated regions',
    'targeted/w_load_tex_use': 'mixed staging and GPR producers',
    'targeted/w_simd_after_load': 'reductions and shuffles after a load',
    'targeted/w_atomic_gpr_operand': 'atomic waiting on staging plus a load',
    'fuzz/fz70': 'end drains an unconsumed load',
    'fuzz2/fz18': 'stall value is the wait restricted to register producers; stall in the constant program',
    'render/fs_tex2/__TEXT___fragment/__TEXT___text': 'fragment: dependent texture sample',
    'render/fs_light/__TEXT___vertex/__TEXT___text': 'vertex: attribute loads and uvsw staging',
    'targeted-fast/w_loop_after_load': 'exec-mask push counts and pop counts',
    'intuni/u32_rotate': 'integer uniform corpus',
}

lines = {}
for path in sys.argv[1:]:
    for l in open(path):
        parts = l.split()
        if len(parts) == 3:
            lines[parts[0]] = parts
o = ['/* Generated by src/asahi/compiler/test/probes/g15g-stalls/gen-test-vectors.py',
     ' * from Apple metal-nt output (AIR-NT 32023.921, -arch applegpu_g15g).',
     ' * input: Apple G15G code with every stall removed and b/bn displacements',
     ' * recomputed; expected: Apple G15G code. Do not edit by hand. */',
     '', 'struct g15g_stall_vector { const char *name, *why, *input, *expected; };',
     '', 'static const struct g15g_stall_vector g15g_stall_vectors[] = {']
for name, why in SELECTED.items():
    if name not in lines:
        sys.exit(f'missing vector {name}')
    _, a, b = lines[name]
    o.append(f'   {{"{name}", "{why}",')
    for label, h in (('in', a), ('ex', b)):
        chunks = [h[i:i + 72] for i in range(0, len(h), 72)]
        o.append('    ' + '\n    '.join(f'"{c}"' for c in chunks) + (',' if label == 'in' else '},'))
o.append('};')
print('\n'.join(o))
