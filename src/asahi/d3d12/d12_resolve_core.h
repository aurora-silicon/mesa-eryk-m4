enum d12_resolve_core_mode {
   D12_RESOLVE_CORE_MODE_MIN = 1,
   D12_RESOLVE_CORE_MODE_MAX = 2,
   D12_RESOLVE_CORE_MODE_AVERAGE = 3,
};

enum d12_resolve_core_mode_mask {
   D12_RESOLVE_CORE_SUPPORT_MIN = UINT32_C(1) << 0,
   D12_RESOLVE_CORE_SUPPORT_MAX = UINT32_C(1) << 1,
   D12_RESOLVE_CORE_SUPPORT_AVERAGE = UINT32_C(1) << 2,
};

enum d12_resolve_core_value_class {
   D12_RESOLVE_CORE_VALUE_FLOAT = 0,
   D12_RESOLVE_CORE_VALUE_UINT = 1,
   D12_RESOLVE_CORE_VALUE_SINT = 2,
};

struct d12_resolve_core_format_info {
   uint32_t shader_format;
   uint32_t pixel_size_B;
   uint32_t mode_mask;
   uint32_t value_class;
};

bool d12_resolve_core_get_format(uint32_t format,
                                 struct d12_resolve_core_format_info *info);
bool d12_resolve_core_supports_mode(uint32_t format, uint32_t mode);
bool d12_resolve_core_supports_average(uint32_t format);
bool d12_resolve_core_resource_compatible(uint32_t resource_format,
                                          uint32_t resolve_format);
