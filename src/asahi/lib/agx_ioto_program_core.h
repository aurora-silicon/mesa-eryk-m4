/* Exact runtime relocations applied by Apple's G17S ComputeContext before
 * enqueue.  gather_buffer_va is emitUscStateLoad's x3 argument.  The root
 * uniform address is user_compute_argument_gpu_va_1 plus the relocation's
 * witnessed 0x8000 addend.  The absolute UniformData source is constructor-
 * owned rather than an enqueue relocation, so the caller supplies the exact
 * VA used to construct this program. */
struct agx_ioto_g17s_minimal_compute_resources {
   uint64_t gather_buffer_va;
   uint64_t user_compute_argument_gpu_va_1;
   uint64_t absolute_uniform_data_va;
};

/*
 * Compose the bounded direct-profile no-PIXREL program form recovered from
 * Apple's AGX3 state-load encoder:
 *
 *    validated scheduled body
 *    SETPROFILECTL
 *    LoadShader state tail (SPECLM is omitted for tail type 1)
 *    exactly one terminal preshader suffix
 *
 * The body may contain only non-control records whose target-specific byte
 * boundaries can be decoded exactly; ambiguous encodings are rejected.
 * State-tail, profile, branch/call/return and pixel-protocol records are
 * rejected.  Program-kind and PIXREL modes are intentionally not exposed by
 * this bounded API.  In particular, this is not the G17S ordinary minimal
 * profile path, whose loader and COPY records have a different exact order;
 * use agx_ioto_g17s_minimal_compute_program_compose for that witness.
 *
 * program_va is the address consumed separately by the AGX3 CDM/VDM pipeline
 * pointer and must therefore be a 48-bit, 64-byte-aligned GPU virtual address.
 * It is validation metadata and is not embedded in the program bytes.
 *
 * The operation is transactional: output and *written are unchanged on every
 * failure.  body may be NULL only when body_size is zero and may overlap
 * output on success.  preshader code may also overlap output.
 */
bool agx_ioto_program_compose_no_pixrel(
   enum agx_chip chip, uint64_t program_va, const void *body, size_t body_size,
   const struct agx_ioto_state_tail *tail,
   const struct agx_ioto_profile_control *profile,
   const struct agx_ioto_preshader_desc *preshader, void *output,
   size_t capacity, size_t *written);

/* Convenience form whose sole terminal suffix is little-endian 0x0000000e. */
bool agx_ioto_straight_line_program_compose(
   enum agx_chip chip, uint64_t program_va, const void *body, size_t body_size,
   const struct agx_ioto_state_tail *tail,
   const struct agx_ioto_profile_control *profile, void *output,
   size_t capacity, size_t *written);

/* Compose the exact 196-byte G17P direct-add3 Ioto program recovered in the
 * SPDX-MIT m1n1 NATIVE_ADD3_SHADER witness. The two fixed scheduled regions
 * surround a semantic runtime state tail. Only the witnessed launch-header
 * fields and shader address are relocated. This is a bounded bring-up
 * program, not general compute feature admission. */
bool agx_ioto_g17p_direct_add3_program_compose(
   uint64_t program_va, uint64_t shader_va, void *output, size_t capacity,
   size_t *written);

/* Compose the G17P program form used when the state loader has no resource
 * records.  Apple's program is one packed type-0 state tail, the 58-byte
 * default profile loader, and the four-byte terminal record.  program_va
 * identifies the separately uploaded, 64-byte-aligned program.
 *
 * The packed form is required because the hardware-positive G17P fragment
 * tail contains runtime SPECLM bits which the anonymous semantic field map
 * does not name yet.  Each record is still checked against the G17P Ioto
 * grammar before publication.  This function does not add uniform, texture,
 * sampler, image, or driver argument loads.  Output and *written are unchanged
 * when validation fails. */
bool agx_ioto_g17p_no_resource_program_compose(
   uint64_t program_va, const struct agx_ioto_state_tail_output *packed_tail,
   void *output, size_t capacity, size_t *written);

/* Compose the ordinary no-resource G17P fragment-stage program captured in
 * every valid EXP-G1a vary0-class run.  Unlike compute and vertex programs,
 * the fragment loader terminates its default profile prefix with the exact
 * six-byte PIXREL record before stop; it has no SETPROFILECTL suffix. */
bool agx_ioto_g17p_fragment_no_resource_program_compose(
   uint64_t program_va, const struct agx_ioto_state_tail_output *packed_tail,
   void *output, size_t capacity, size_t *written);

/* Compose a G17P resource program around a body emitted by the HAL200 ESL
 * scheduler. Resource loads and their drain padding precede the packed shader
 * state. The default profile loader then copies those results into CProg and
 * terminates. pre_copy_body and copies are validated as separate record spans;
 * the latter may contain COPY records only. */
bool agx_ioto_g17p_resource_program_compose(
   uint64_t program_va, const void *pre_copy_body, size_t pre_copy_body_size,
   const void *copies, size_t copies_size,
   const struct agx_ioto_state_tail_output *packed_tail, void *output,
   size_t capacity, size_t *written);

/* The resource-bearing fragment form has the same scheduled loads, shader
 * tail, profile prefix and COPY body, but closes with PIXREL instead of the
 * vertex/compute SETPROFILECTL suffix. */
bool agx_ioto_g17p_fragment_resource_program_compose(
   uint64_t program_va, const void *pre_copy_body, size_t pre_copy_body_size,
   const void *copies, size_t copies_size,
   const struct agx_ioto_state_tail_output *packed_tail, void *output,
   size_t capacity, size_t *written);

/* Internal background clear/reload programs with no shader pixel-dependency
 * operations use the native BG PIXREL descriptor 0x200, not ordinary FS
 * 0x2f3. The scheduled-load and COPY validation is identical to the other
 * resource composers. This is not a general replacement for fragment state.
 */
bool agx_ioto_g17p_background_resource_program_compose(
   uint64_t program_va, const void *pre_copy_body, size_t pre_copy_body_size,
   const void *copies, size_t copies_size,
   const struct agx_ioto_state_tail_output *packed_tail, void *output,
   size_t capacity, size_t *written);

/* Compose the complete byte-for-byte G17S minimal root-uniform/no-texture
 * compute Ioto program: fixed resource loads, semantic state tail, the real
 * 52-byte minimal-profile loader, eight witnessed COPY records, and terminal
 * suffix.  Only shader_va is patched.  The fixed body contains a two-dword
 * gather load, the buffer(1) root-uniform load, and a witnessed three-dword
 * absolute load.  The root uniform is copied from half24 to CProg half8.  The
 * first COPY pair transfers the same logical kind-3 Register zero passed to
 * addBufferPointerLoad by loadImmediateUserBuffer, so it carries the low/high
 * halves of the relocated user-buffer pointer into CProg dwords 2..3.  This
 * template form leaves the two runtime address pairs zero.  Output and
 * *written are transactional. */
bool agx_ioto_g17s_minimal_compute_program_compose(
   uint64_t program_va, uint64_t shader_va, void *output, size_t capacity,
   size_t *written);

/* Apply the two exact host-side G17S relocations and the constructor-owned
 * absolute UniformData source.  The six LDIMM records remain the witnessed
 * eight-byte ep2 forms even when an address half could use a short encoding.
 * Output and *written are unchanged on every failure. */
bool agx_ioto_g17s_minimal_compute_program_compose_resources(
   uint64_t program_va, uint64_t shader_va,
   const struct agx_ioto_g17s_minimal_compute_resources *resources,
   void *output, size_t capacity, size_t *written);

